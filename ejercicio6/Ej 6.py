pais = input("Introduce un país: ")

if pais=="España" or pais=="Francia" or pais=="Italia":
    print(f"El país {pais} está en Europa")
elif pais=="Japón" or pais=="China" or pais=="India":
    print(f"El país {pais} está en Asia")
elif pais=="Egipto" or pais=="Kenia" or pais=="Marruecos":
    print(f"El país {pais} está en África")
elif pais=="México" or pais=="Brasil" or pais=="Canadá":
    print(f"El país {pais} está en América")